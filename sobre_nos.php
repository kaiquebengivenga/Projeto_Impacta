                <p>
                Somos o School Points, um projeto que nasceu da nossa inquietação com a falta de motivação dos alunos no ambiente acadêmico. Muitas vezes, vemos jovens desmotivados, sem enxergar um propósito claro em sua educação, indo à escola apenas porque são forçados por seus pais. Essa desmotivação nos deixou pensando: como podemos inspirar os alunos a perseguirem o próprio aprendizado, incentivando-os a desejar estudar?
                </p>
                <br>
                <p>
                A resposta para essa pergunta é o School Points. Desenvolvemos uma plataforma inovadora, um site, que funciona de uma maneira simples e eficaz. A cada bimestre, os alunos recebem uma quantidade de pontos com base em seu desempenho acadêmico. No entanto, esses pontos não são apenas números; eles são uma oportunidade para alcançar algo significativo que esteja alinhado com seus interesses pessoais, ao mesmo tempo em que fomentam o crescimento cultural e acadêmico.
                </p>
                <br>
                <p>
                Imagine poder trocar seus pontos por livros que alimentam sua mente e ampliam seus horizontes, ou obter descontos em cursos que aprimoram suas habilidades. O School Points também oferece benefícios práticos, como descontos em cantinas escolares e até mesmo em alguns restaurantes locais. Acreditamos que, ao oferecer recompensas tangíveis e motivadoras, podemos estimular um desejo genuíno de aprender.
